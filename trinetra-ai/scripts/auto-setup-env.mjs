#!/usr/bin/env node
/**
 * AUTO-SETUP — ensures Sentinel live camera credentials are auto-configured
 * so website runs without manual email/password entry.
 * 
 * Called automatically on `npm run dev` via predev hook, or manually:
 *   node scripts/auto-setup-env.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const HACKATHON_CREDS = {
  email: 'himesh.rupchandani140850@marwadiuniversity.ac.in',
  password: 'A7UX-7TRC-BVS6',
  whepOrigin: 'http://103.250.160.189:8889',
  hlsOrigin: 'http://103.250.160.189:80',
};

function ensureEnvFile(filePath, isLocal = false) {
  const exists = fs.existsSync(filePath);
  let content = exists ? fs.readFileSync(filePath, 'utf8') : '';

  const hasEmail = content.includes('SENTINEL_EMAIL') && /SENTINEL_EMAIL\s*=\s*\S+/.test(content);
  const hasPassword = content.includes('SENTINEL_PASSWORD') && /SENTINEL_PASSWORD\s*=\s*\S+/.test(content);

  if (hasEmail && hasPassword) {
    console.log(`✅ ${path.basename(filePath)} already has credentials`);
    return;
  }

  // Build auto-configured env
  const autoContent = `# AUTO-CONFIGURED — hackathon live cameras, no manual login needed
# Generated by scripts/auto-setup-env.mjs
VITE_USE_MOCKS=false
VITE_API_BASE_URL=/api
BACKEND_ORIGIN=http://localhost:8000
VITE_REALTIME_TRANSPORT=sse
VITE_MAP_CENTER_LAT=22.3000
VITE_MAP_CENTER_LNG=71.6000
VITE_MAP_DEFAULT_ZOOM=7
SENTINEL_WHEP_ORIGIN=${HACKATHON_CREDS.whepOrigin}
SENTINEL_HLS_ORIGIN=${HACKATHON_CREDS.hlsOrigin}
SENTINEL_EMAIL=${HACKATHON_CREDS.email}
SENTINEL_PASSWORD=${HACKATHON_CREDS.password}
VITE_STREAM_BASE_PATH=/sentinel/stream
VITE_LIVE_STREAMS=true
VITE_AUTO_LOGIN=true
VITE_DEFAULT_LIVE_CAMERA=cam04
`;

  if (!exists || !content.trim()) {
    fs.writeFileSync(filePath, autoContent, 'utf8');
    console.log(`✅ Created ${path.basename(filePath)} with auto-login credentials`);
  } else {
    // Patch existing file — inject missing credentials
    let updated = content;
    if (!hasEmail) {
      updated = updated.replace(/SENTINEL_EMAIL\s*=.*/g, '').trim() + `\nSENTINEL_EMAIL=${HACKATHON_CREDS.email}\n`;
    } else {
      updated = updated.replace(/SENTINEL_EMAIL\s*=.*/g, `SENTINEL_EMAIL=${HACKATHON_CREDS.email}`);
    }
    if (!hasPassword) {
      updated = updated.replace(/SENTINEL_PASSWORD\s*=.*/g, '').trim() + `\nSENTINEL_PASSWORD=${HACKATHON_CREDS.password}\n`;
    } else {
      updated = updated.replace(/SENTINEL_PASSWORD\s*=.*/g, `SENTINEL_PASSWORD=${HACKATHON_CREDS.password}`);
    }
    // Ensure live flags
    if (!updated.includes('VITE_LIVE_STREAMS')) updated += '\nVITE_LIVE_STREAMS=true\n';
    if (!updated.includes('VITE_AUTO_LOGIN')) updated += '\nVITE_AUTO_LOGIN=true\n';
    fs.writeFileSync(filePath, updated, 'utf8');
    console.log(`✅ Patched ${path.basename(filePath)} with auto-login credentials`);
  }
}

// Frontend
ensureEnvFile(path.join(root, '.env'));
ensureEnvFile(path.join(root, '.env.local'), true);

// Backend
const backendEnvPath = path.resolve(root, '..', 'TRINETRAAI', 'backend', '.env');
const backendExamplePath = path.resolve(root, '..', 'TRINETRAAI', 'backend', '.env.example');

if (!fs.existsSync(backendEnvPath)) {
  const example = fs.existsSync(backendExamplePath) ? fs.readFileSync(backendExamplePath, 'utf8') : '';
  let backendContent = example;
  // Replace placeholders with real creds
  backendContent = backendContent.replace(/SENTINEL_EMAIL=.*/g, `SENTINEL_EMAIL=${HACKATHON_CREDS.email}`);
  backendContent = backendContent.replace(/SENTINEL_PASSWORD=.*/g, `SENTINEL_PASSWORD=${HACKATHON_CREDS.password}`);
  if (!backendContent.includes(HACKATHON_CREDS.email)) {
    backendContent += `\nSENTINEL_EMAIL=${HACKATHON_CREDS.email}\nSENTINEL_PASSWORD=${HACKATHON_CREDS.password}\n`;
  }
  backendContent = backendContent.replace(/AUTO_START_CAMERAS=false/g, 'AUTO_START_CAMERAS=true');
  fs.writeFileSync(backendEnvPath, backendContent, 'utf8');
  console.log(`✅ Created backend .env at ${backendEnvPath}`);
} else {
  console.log(`✅ Backend .env exists at ${backendEnvPath}`);
}

console.log('\n🎬 Auto-setup complete — live camera will auto-connect, no manual email/password needed');
console.log('   Run: npm run dev (frontend) + uvicorn in backend');
