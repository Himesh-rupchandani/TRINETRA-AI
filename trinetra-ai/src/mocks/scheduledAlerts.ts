let globalTick = 0;

export function buildScheduledAlertPair(index?: number): {
  event: VehicleEvent;
  alert: Alert;
  template: ScheduledAlertTemplate;
} {
  const i = (index !== undefined ? index : globalTick++) % SCHEDULED_ALERTS.length;
  const tmpl = SCHEDULED_ALERTS[i];
  const now = new Date().toISOString();
  const eventId = `evt-sched-${Date.now()}-${i}`;
  const alertId = `alr-sched-${Date.now()}-${i}`;
  const confidence = Number((92 + Math.random() * 7).toFixed(1));
  const ref = `ev/${tmpl.cameraId}/${eventId}`;

  const event: VehicleEvent = {
    id: eventId,
    cameraId: tmpl.cameraId,
    cameraName: tmpl.cameraName,
    plate: tmpl.plate,
    plateConfidence: confidence,
    timestamp: now,
    latitude: tmpl.latitude,
    longitude: tmpl.longitude,
    location: tmpl.location,
    vehicleClass: tmpl.vehicleClass,
    eventType: 'WATCHLIST_MATCH',
    severity: tmpl.severity,
    watchlistMatch: true,
    speedKmph: Math.round(45 + Math.random() * 30),
    evidenceRef: ref,
    evidence: {
      ref,
      capturedAt: now,
      synthetic: true,
      frameUrl: syntheticFrame({
        cameraName: tmpl.cameraName,
        location: tmpl.location,
        plate: tmpl.plate,
        timestamp: now,
        vehicleClass: tmpl.vehicleClass,
      }),
      plateCropUrl: syntheticPlateCrop(tmpl.plate, confidence),
    },
  };

  const alert: Alert = {
    id: alertId,
    eventId,
    plate: tmpl.plate,
    cameraId: tmpl.cameraId,
    cameraName: tmpl.cameraName,
    location: tmpl.location,
    latitude: tmpl.latitude,
    longitude: tmpl.longitude,
    severity: tmpl.severity,
    status: 'NEW',
    category: tmpl.category,
    createdAt: now,
    confidence,
    evidenceRef: ref,
    note: `[ANPR Hit] ${tmpl.vehicleModel} detected on ${tmpl.cameraName} (${tmpl.location}). Reason: ${tmpl.reason}`,
  };

  return { event, alert, template: tmpl };
}
