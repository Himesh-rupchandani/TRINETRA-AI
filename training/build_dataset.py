#!/usr/bin/env python3
"""
PART 4c — validate the dataset and emit the Ultralytics data YAML.

Checks that actually catch the mistakes that ruin a small dataset:

* every image has a label file (an empty one is a valid negative);
* label values are inside [0, 1] and boxes are non-degenerate;
* **no leakage**: no frame index from one time segment appears in two splits,
  and no source video contributes the *same* segment to two splits;
* the val/test splits are not empty and actually contain plates.

Usage:
    python training/build_dataset.py --dataset training/dataset
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import List

SPLITS = ("train", "val", "test")


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", default="training/dataset")
    ap.add_argument("--class-name", default="plate")
    args = ap.parse_args(argv)

    root = Path(args.dataset).resolve()
    problems: List[str] = []
    stats = {s: {"images": 0, "labelled": 0, "boxes": 0} for s in SPLITS}

    for split in SPLITS:
        img_dir, lbl_dir = root / "images" / split, root / "labels" / split
        if not img_dir.is_dir():
            problems.append(f"missing image directory: {img_dir}")
            continue
        for img in sorted(img_dir.glob("*.jpg")):
            stats[split]["images"] += 1
            lbl = lbl_dir / f"{img.stem}.txt"
            if not lbl.exists():
                problems.append(f"no label file for {img.name} (create an empty one for a negative)")
                continue
            text = lbl.read_text().strip()
            if not text:
                continue
            stats[split]["labelled"] += 1
            for ln, line in enumerate(text.splitlines(), 1):
                parts = line.split()
                if len(parts) != 5:
                    problems.append(f"{lbl.name}:{ln} expected 5 values, got {len(parts)}")
                    continue
                try:
                    _c, cx, cy, bw, bh = int(parts[0]), *map(float, parts[1:])
                except ValueError:
                    problems.append(f"{lbl.name}:{ln} non-numeric values")
                    continue
                if not all(0.0 <= v <= 1.0 for v in (cx, cy, bw, bh)):
                    problems.append(f"{lbl.name}:{ln} coordinates outside [0,1]")
                if bw <= 0 or bh <= 0:
                    problems.append(f"{lbl.name}:{ln} degenerate box")
                stats[split]["boxes"] += 1

    # ---- leakage check, using the manifest written by extract_frames.py ----
    manifest_path = root / "manifest.json"
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text())
        seg_split = defaultdict(set)
        for m in manifest:
            seg_split[(m["source_video"], m["segment"])].add(m["split"])
        for (video, seg), splits in sorted(seg_split.items()):
            if len(splits) > 1:
                problems.append(
                    f"LEAKAGE: {Path(video).name} segment {seg} appears in {sorted(splits)}"
                )
    else:
        problems.append("no manifest.json — run extract_frames.py so leakage can be verified")

    for split in ("val", "test"):
        if stats[split]["images"] == 0:
            problems.append(f"{split} split is empty — you cannot evaluate honestly without it")
        elif stats[split]["labelled"] == 0:
            problems.append(f"{split} split has no positive labels")

    yaml_path = root / "plates.yaml"
    yaml_path.parent.mkdir(parents=True, exist_ok=True)
    yaml_path.write_text(
        "# Generated by training/build_dataset.py — do not edit by hand.\n"
        f"path: {root}\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n"
        "names:\n"
        f"  0: {args.class_name}\n"
    )

    for split in SPLITS:
        s = stats[split]
        print(f"[dataset] {split:5s} images={s['images']:4d} "
              f"with-plate={s['labelled']:4d} boxes={s['boxes']:4d}")
    print(f"[dataset] data yaml -> {yaml_path}")
    if problems:
        print(f"\n[dataset] {len(problems)} PROBLEM(S):")
        for p in problems[:40]:
            print(f"  - {p}")
        if len(problems) > 40:
            print(f"  … and {len(problems) - 40} more")
        return 1
    print("[dataset] OK — splits are clean and leakage-free.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
